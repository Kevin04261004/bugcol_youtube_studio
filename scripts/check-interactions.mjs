import {Window} from 'happy-dom';
import {build} from 'esbuild';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const window=new Window({url:'https://example.test',settings:{disableCSSFileLoading:true,disableJavaScriptFileLoading:true}});
window.document.write(fs.readFileSync('dist/index.html','utf8').replace(/<script[^>]*>[\s\S]*?<\/script>/g,''));
window.HTMLCanvasElement.prototype.getContext=()=>new Proxy({measureText:t=>({width:t.length*12})},{get:(o,k)=>o[k]||(()=>{})});
window.confirm=()=>true;
window.structuredClone=structuredClone;
const registered=new Map();window.document.modelContext={registerTool:async tool=>registered.set(tool.name,tool)};
await build({entryPoints:['dist/app.js'],bundle:true,write:false,format:'esm'});
const errors=[];window.addEventListener('error',e=>errors.push(e.message));
window.fetch=async()=>new window.Response(JSON.stringify({user:null}),{status:200,headers:{'Content-Type':'application/json'}});
const result=await build({entryPoints:['dist/app.js'],bundle:true,write:false,format:'esm'});
window.eval('(async()=>{'+result.outputFiles[0].text+'})()');
await new Promise(r=>setTimeout(r,100));
window.document.getElementById('sampleBtn').click();
await new Promise(r=>setTimeout(r,50));
assert.ok(window.document.querySelectorAll('.sentence-item').length>=3,'Sample button must create sentences');
window.document.querySelector('[data-tab="scenes"]').click();
assert.equal(window.document.getElementById('scenesView').hidden,false);
window.document.getElementById('goExport').click();
assert.equal(window.document.getElementById('exportView').hidden,false);
window.document.getElementById('addSentence').click();
assert.equal(window.document.getElementById('sentenceText').value,'');
const read=registered.get('get_longform_project');assert.ok(read);
const edit=registered.get('update_longform_scenes');assert.ok(edit);
edit.execute({scenes:[{id:1,title:'검사 장면'}]});
assert.equal(read.execute().sentences[0].scene.title,'검사 장면');
assert.throws(()=>edit.execute({scenes:[{id:999999,title:'실패'}]}));
assert.deepEqual(errors,[]);
console.log('PASS sample creation, scene navigation, export navigation');
await window.happyDOM.abort();
